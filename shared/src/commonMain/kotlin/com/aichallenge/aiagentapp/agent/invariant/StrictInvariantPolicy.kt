package com.aichallenge.aiagentapp.agent.invariant

/**
 * Единая семантика: инварианты — строгие ограничения, не рекомендации.
 */
object StrictInvariantPolicy {

    val injectedPreamble: String = """
        |ИНВАРИАНТЫ — СТРОГИЕ ОГРАНИЧЕНИЯ (обязательны к исполнению):
        |• Каждое правило ниже обязательно. Это не советы и не «по возможности».
        |• Правило-предпочтение («Kotlin», «Compose», «symphonic metal») означает: использовать ИСКЛЮЧИТЕЛЬНО указанное; альтернативы из той же категории запрещены.
        |• «только X» / «язык — только X» = категорически X, без замен.
        |• «Не использовать Y» = Y полностью исключён из ответа и рекомендаций.
        |• Если запрос пользователя противоречит правилам — откажи и предложи вариант строго в рамках инвариантов.
    """.trimMargin()

    val classifierRules: String = """
        |ИНВАРИАНТЫ — СТРОГИЕ ограничения:
        |• Предпочтения в блоке («Kotlin», «symphonic metal», «Room») = обязательный выбор, не опция.
        |• «только X» запрещает любую замену X в той же категории (другой язык, жанр, фреймворк).
        |• Запрос, требующий нарушить предпочтение или запрет, = конфликт.
        |• Ответ, рекомендующий альтернативу вне стека/жанра блока, = нарушение.
    """.trimMargin()

    val conflictRules: String = """
        |hasConflict=true, если запрос КАК НАПИСАН потребует нарушить любое правило:
        |• Явный запрет («Не использовать Java») + просьба про Java.
        |• «только Kotlin» / «Kotlin» как обязательный язык + просьба кода на C#, Java, Python и т.д.
        |• «Compose» как UI + просьба XML/View system.
        |• «symphonic metal» как жанр + просьба jazz/pop/rock.
        |• Любое предпочтение блока + явная просьба противоположного/альтернативного из той же категории.
    """.trimMargin()

    val validationRules: String = """
        |pass=false, если ответ нарушает ЛЮБОЕ правило блока:
        |• Рекомендует или показывает запрещённое («Не использовать X»).
        |• Использует другой язык/жанр/стек вместо обязательного предпочтения блока.
        |• «только Kotlin» → код/примеры на C#, Java, Python и др.
        |• «Compose» → UI на XML/Views без Compose.
        |• «symphonic metal» → рекомендации другого жанра.
        |• Частичное соблюдение недостаточно: стек и жанр должны совпадать строго.
    """.trimMargin()
}
