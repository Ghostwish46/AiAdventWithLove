package com.aichallenge.aiagentapp.agent.task

object TaskStatePromptBuilder {

    fun buildSystemPrompt(basePrompt: String, taskState: TaskState): String {
        if (!taskState.isActive) return basePrompt
        return buildString {
            append(basePrompt)
            append("\n\n--- СОСТОЯНИЕ ЗАДАЧИ ---")
            append("\nЭтап: ${taskState.phase.name.lowercase()} (${taskState.phase.displayName})")
            if (!taskState.currentStep.isBlank()) {
                append("\nТекущий шаг: ${taskState.currentStep}")
            }
            if (!taskState.expectedAction.isBlank()) {
                append("\nОжидаемое действие: ${taskState.expectedAction}")
            }
            if (!taskState.taskGoal.isNullOrBlank()) {
                append("\nЦель задачи: ${taskState.taskGoal}")
            }
            if (taskState.planningFacts.isNotEmpty()) {
                append("\nСобранные факты (planning):")
                taskState.planningFacts.forEach { (k, v) -> append("\n  $k: $v") }
            }
            if (taskState.openQuestions.isNotEmpty()) {
                append("\nОткрытые вопросы (ждут ответа):")
                taskState.openQuestions.forEachIndexed { i, q ->
                    append("\n  ${i + 1}. $q")
                }
            }
            if (taskState.completedSteps.isNotEmpty()) {
                append("\nВыполненные шаги: ${taskState.completedSteps.joinToString("; ")}")
            }
            when (taskState.phase) {
                TaskPhase.PLANNING -> appendPlanningRules(taskState)
                TaskPhase.EXECUTION -> appendExecutionRules()
                TaskPhase.VALIDATION -> appendValidationRules(taskState)
                TaskPhase.DONE -> append(
                    "\n\nЗадача завершена. Отвечай на уточнения по результату или помогай с новой задачей."
                )
            }
        }
    }

    private fun StringBuilder.appendPlanningRules(taskState: TaskState) {
        append("\n\n--- ПРАВИЛА ЭТАПА PLANNING ---")
        append(
            "\n1. Сначала собери все нужные уточнения. При первом контакте по задаче задай СРАЗУ ВСЕ ключевые " +
                "уточняющие вопросы одним нумерованным списком (обычно 3–7 пунктов). НЕ задавай их по одному в разных сообщениях."
        )
        append(
            "\n2. Пользователь может ответить сразу на несколько вопросов в одном сообщении — прими и зафиксируй все ответы."
        )
        append(
            "\n3. ЗАПРЕЩЕНО додумывать, подставлять значения по умолчанию или переходить к плану/выводам, " +
                "пока есть открытые вопросы без ответа."
        )
        append(
            "\n4. Исключение — только если пользователь явно пишет: «на своё усмотрение», «пропусти», " +
                "«не важно», «решай сам» (тогда зафиксируй это в фактах и убери вопрос из открытых)."
        )
        append(
            "\n5. Если пользователь ответил частично — поблагодари, зафиксируй полученные ответы и " +
                "напомни списком только ОСТАВШИЕСЯ неотвеченные вопросы. Не переспрашивай уже закрытые."
        )
        append(
            "\n6. Можешь добавлять новые уточняющие вопросы по ходу (тоже списком), если ответ выявил новую неясность."
        )
        append(
            "\n7. Переход к execution (готовый план, структура, черновик) — только когда открытых вопросов нет " +
                "или пользователь явно просит начать работу."
        )
        when {
            taskState.openQuestions.isEmpty() && taskState.planningFacts.isEmpty() -> append(
                "\n\nСейчас приоритет: сформулировать и задать сразу полный список уточняющих вопросов по задаче."
            )
            taskState.openQuestions.isNotEmpty() -> append(
                "\n\nСейчас приоритет: принять ответы пользователя и напомнить о неотвеченных вопросах списком. " +
                    "Не выдавай финальный план, пока открытые вопросы не закрыты."
            )
        }
    }

    private fun StringBuilder.appendExecutionRules() {
        append("\n\n--- ПРАВИЛА ЭТАПА EXECUTION ---")
        append(
            "\n1. Выполняй задачу по собранным фактам и плану. Не переспрашивай цель и контекст — они зафиксированы выше."
        )
        append(
            "\n2. Выдавай содержательный результат (черновик, структура, материалы) — не только описание того, что собираешься сделать."
        )
        append(
            "\n3. После готовности основного результата переходи к проверке (validation): результат нужно будет оценить с разных ролей."
        )
    }

    private fun StringBuilder.appendValidationRules(taskState: TaskState) {
        append("\n\n--- ПРАВИЛА ЭТАПА VALIDATION ---")
        append(
            "\n1. Это этап проверки и улучшения готового результата. Оцени решение с НЕСКОЛЬКИХ ролей/перспектив, " +
                "релевантных типу задачи. Не ограничивайся одним общим «всё хорошо»."
        )
        append(
            "\n2. Базовые перспективы (адаптируй под задачу):"
        )
        append(
            "\n   • Эксперт в предметной области — фактическая точность, актуальность, устаревшие подходы и практики, " +
                "соответствие современным стандартам, пробелы в аргументации."
        )
        append(
            "\n   • Целевая аудитория / слушатель / читатель — понятность, интерес, не будет ли скучно или неактуально, " +
                "достаточность контекста для уровня аудитории."
        )
        append(
            "\n   • Исполнитель (спикер, автор, разработчик) — практические заметки: паузы, переходы между блоками, " +
                "акценты, что подчеркнуть устно, что сократить, риски при подаче."
        )
        append(
            "\n   • Критик / рецензент — слабые места, противоречия, что вызовет вопросы или возражения."
        )
        append(
            "\n3. ОБЯЗАТЕЛЬНО явно отчитайся о проверке текущего решения. В каждом validation-ответе должен быть " +
                "видимый блок «Отчёт о проверке» (или аналогичный заголовок) с итогами по каждой перспективе: " +
                "что проверено, вердикт, найденные проблемы. Не переходи сразу к улучшениям без отчёта."
        )
        append(
            "\n4. Для каждой перспективы в отчёте: краткий вердикт + конкретные замечания (не абстрактные)."
        )
        append(
            "\n5. После отчёта — улучши результат, если это возможно: исправь ошибки, обнови устаревшее, " +
                "добавь недостающее, предложи улучшенную версию или блок «Что изменить» с приоритетами."
        )
        append(
            "\n6. Пример для доклада: эксперт проверяет актуальность технологий; слушатель — не скучны ли разделы; " +
                "спикер получает заметки по паузам, переходам и акцентам на каждый блок."
        )
        append(
            "\n7. Не возвращайся к planning-вопросам, если контекст уже собран. Фокус — на качестве готового результата."
        )
        append(
            "\n8. Завершай validation только после явного отчёта о проверке, мульти-перспективной оценки и предложенных улучшений."
        )
        if (taskState.currentStep.isNotBlank()) {
            append("\n\nСейчас в validation: ${taskState.currentStep}.")
        } else {
            append(
                "\n\nСейчас приоритет: явно отчитаться о проверке текущего решения (блок «Отчёт о проверке»), " +
                    "затем выдать улучшенный результат или список правок."
            )
        }
    }
}
